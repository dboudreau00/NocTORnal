"""Invariants that live in the documentation rather than in the code.

`SECURITY.md` tells an external security researcher, as the first thing it asks of them, to read
`docs/17-flagged-for-review.md`, the register of what is already known-wrong, so that they do not
report something the project has already recorded. `ARCHITECTURE.md` cites the same file as the
PROVENANCE for its review claims: "reviewed (docs/17 F15, ten service defects)".

If that file is removed from the working tree, every one of those references becomes a link to
nothing, in the two documents whose job is to be trusted by somebody outside this codebase. A citation
to a file that does not exist is worse than no citation: it reads as evidence, and it is checkable
only by the reader, who is the one person who cannot check it.

Pure: no database. These read the shipped documents.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[3]

#: `[text](target.md)` and `[text](target.md#anchor)`. Bare URLs and
#: fenced code are not links and are not checked.
_MD_LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+\.md)(?:#[^)\s]*)?\)")

#: The packaged export is a `git archive` copy of the tree, regenerated by `package_release.ps1`.
#: Checking it would report every finding twice. `.claude` is the agent harness's directory and holds
#: whole worktree copies of the repository while a pass is in flight: without skipping it, a run from
#: the main checkout reads every document in every worktree and reports each finding once per copy,
#: against text this checkout does not contain. `check_source_hygiene.py` skips it for the same reason.
_SKIP_PARTS = {".venv", ".git", "node_modules", ".claude"}
_SKIP_DIRS = ("NocTORnal - Alpha Release",)


def _docs() -> list[Path]:
    out = []
    for md in ROOT.rglob("*.md"):
        # Match on the path RELATIVE to the repository, not the absolute one. The harness checks this
        # tree out under `<main>/.claude/worktrees/`, so an absolute match on `.claude` would skip every
        # document in a worktree and return an empty list, and every check below would pass by doing
        # nothing, which `test_there_are_documents_to_check` exists to catch.
        rel = md.relative_to(ROOT)
        if _SKIP_PARTS & set(rel.parts):
            continue
        if any(d in str(rel) for d in _SKIP_DIRS):
            continue
        out.append(md)
    return sorted(out)


def test_there_are_documents_to_check():
    """A glob that silently matches nothing turns every check below into a
    check that passes by doing nothing — the failure mode this file was
    written about, reappearing in the file itself."""
    docs = _docs()
    assert len(docs) > 20, f"only found {len(docs)} markdown files under {ROOT}"


@pytest.mark.parametrize("doc", _docs(), ids=lambda p: p.name)
def test_every_document_link_resolves(doc: Path):
    """A link to a file that is not in the tree."""
    broken = []
    for target in _MD_LINK.findall(doc.read_text(encoding="utf-8")):
        if target.startswith(("http://", "https://", "mailto:")):
            continue
        if not (doc.parent / target).resolve().exists():
            broken.append(target)
    assert not broken, (
        f"{doc.relative_to(ROOT).as_posix()} links to files that do not "
        f"exist: {broken}")


#: The two documents written for somebody OUTSIDE this codebase. A dangling
#: reference costs more here than anywhere else in the tree, because the
#: reader has no way to tell a missing file from a file they cannot see.
_OUTWARD_FACING = ("SECURITY.md", "README.md", "ARCHITECTURE.md")


@pytest.mark.parametrize("name", _OUTWARD_FACING)
def test_the_outward_facing_documents_cite_files_that_exist(name: str):
    """Belt to the braces above: these three are checked by name so that
    deleting one does not quietly reduce the coverage of this file to the
    documents that happen to remain."""
    doc = ROOT / name
    assert doc.exists(), f"{name} is missing from the repository root"
    missing = [
        target for target in _MD_LINK.findall(doc.read_text(encoding="utf-8"))
        if not target.startswith(("http://", "https://", "mailto:"))
        and not (doc.parent / target).resolve().exists()
    ]
    assert not missing, f"{name} cites missing documents: {missing}"


