"""The one loader for `.env.local`, shared by every script in this directory.

Underscore-prefixed because it is not a command. The one thing it can be asked on the command
line is `export`, for a shell that wants the file's values without running the file:

    eval "$(python scripts/_env.py export)"

The file is data, never a script: every value comes out as one shell-quoted word, so a `$(...)`,
a backtick or a `;` in it is text, where `set -a; . ./.env.local` would execute it.

Every script imports this module rather than a copy of the loader, so none can miss the file.
Without it a script fails with "DATABASE_URL is not set" on a machine whose `.env.local` holds
it, and a NOCTORNAL_TOTP_KEK generated by hand for that shell would seal an account's TOTP secret
under a key the API does not hold, so that every later sign-in fails as `bad_totp`.
"""
from __future__ import annotations

import os
import re
import shlex
import sys
from collections.abc import Iterator
from pathlib import Path


def env_local_path() -> Path:
    """`.env.local` at the project root — the parent of `scripts/`."""
    return Path(__file__).resolve().parent.parent / ".env.local"


#: Names that decide which program or library the next process starts, not what a NocTORnal
#: setting is. Reading `.env.local` as data stops it running as shell syntax, but exporting
#: `PYTHONPATH=./evil` (with a sitecustomize.py), `PATH=./evilbin`, `LD_PRELOAD=./evil.so` or
#: `BASH_ENV=./evil.sh` from it would still run code as this user in the next python or shell,
#: and `DOCKER_CONFIG`, `DOCKER_HOST`, `COMPOSE_*`, `GIT_*`, `PIP_*`, `NODE_OPTIONS` and
#: PowerShell's `PSModulePath` redirect the tools these scripts start the same way. The file
#: names settings; it does not name where programs come from. Not an allow-list on purpose:
#: every new setting would silently stop loading. A real need is met by exporting the variable
#: in your own shell. Matched without regard to case, as Windows treats `Path` and `PATH` as one
#: name. The same list is in release/install.sh, scripts/launch.sh, scripts/launch.ps1 and
#: scripts/open-ui.ps1 (and release/INSTALL.md's one-line loader), and a test holds them to
#: each other.
REFUSED_NAMES = frozenset({
    "PATH", "PATHEXT", "HOME", "COMSPEC", "IFS", "ENV", "CDPATH", "GLOBIGNORE",
    "SHELLOPTS", "BASHOPTS", "PROMPT_COMMAND", "PS1", "PS2", "PS3", "PS4",
    "PSMODULEPATH",
})
REFUSED_PREFIXES = ("BASH_", "LD_", "DYLD_", "PYTHON", "DOCKER_", "COMPOSE_", "GIT_", "PIP_", "NODE_")


def is_refused_name(name: str) -> bool:
    upper = name.upper()
    return upper in REFUSED_NAMES or upper.startswith(REFUSED_PREFIXES)


def _pairs(text: str) -> Iterator[tuple[str, str]]:
    """`(name, value)` for each `NAME=value` line, as `load_env_local` and
    `export_statements` both read them. A name that changes how programs
    start (`is_refused_name`) is left out and said so on stderr, by name and
    never with its value."""
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key, value = key.strip(), value.strip().strip('"').strip("'")
        if key and is_refused_name(key):
            print(f".env.local: ignored {key}, a name that changes how programs start "
                  f"(set it in your shell if you mean it)", file=sys.stderr)
            continue
        if key:
            yield key, value


def _read_env_local() -> str:
    # utf-8-SIG: strips a BOM if one is present (see `load_env_local`).
    return env_local_path().read_text(encoding="utf-8-sig")


_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")


def export_statements() -> list[str]:
    """`export NAME='value'` for every line of `.env.local` whose NAME is not
    already in the environment, each value one `shlex.quote`d word.

    The same precedence as `load_env_local`: what is already set wins, empty
    included. A name that is not a plain identifier is left out rather than
    quoted, because there is nothing a shell could safely do with it."""
    try:
        text = _read_env_local()
    except OSError:
        return []
    return [f"export {key}={shlex.quote(value)}" for key, value in _pairs(text)
            if _NAME.match(key) and key not in os.environ]


def load_env_local() -> None:
    """Load `.env.local` into `os.environ`, without overriding it.

    Existing environment variables win, so a deliberately exported DATABASE_URL is never
    replaced by the file. A variable that is defined but empty wins too: every variable here
    gates something, and an operator who blanks `SMTP_ALLOW_PLAINTEXT` to turn plaintext SMTP
    off must not have the file's `1` reinstated. `noctornal_api.db.dsn()` tells "set but empty"
    from "not set", so this rule does not present as a missing value. A missing file is not an
    error: a developer may work from an exported environment.
    """
    try:
        # utf-8-sig strips a BOM if there is one and is plain utf-8 otherwise. A file edited in
        # Notepad, or written by an older installer, can carry one, and a BOM silently renames
        # the first key, which then presents as "the KEK is not set" with the KEK in the file.
        text = _read_env_local()
    except OSError:
        return
    for key, value in _pairs(text):
        if key not in os.environ:
            os.environ[key] = value


if __name__ == "__main__":
    if sys.argv[1:] == ["export"]:
        statements = export_statements()
        if statements:
            print("\n".join(statements))
        raise SystemExit(0)
    raise SystemExit("scripts/_env.py is a module, not a command; "
                     "the one thing it answers is `export`.")
